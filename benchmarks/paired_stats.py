"""Exact paired significance tests shared across benchmark rounds.

Lifted out rather than re-derived: ``benchmarks/screening_round/arms.py``'s ``_sign_test``
(:901) is the same two-sided exact binomial on discordant pairs that this repository has used
for every 480-seed McNemar comparison to date (``docs/EVOLVE_SEARCH_PLAN.md`` sections 3.4.4,
3.5, 3.7; ``docs/DE_KERNEL_PLAN.md`` clause 3). ``arms.py`` itself is not edited or imported --
it backs published numbers and stays exactly as it is -- this module is the one other rounds
should import from instead of re-typing the formula.
"""

from __future__ import annotations

import math


def mcnemar_exact(a_only: int, b_only: int) -> float:
    """Two-sided exact McNemar p-value on paired outcomes, ties (both/neither) discarded.

    ``a_only`` and ``b_only`` are the counts of pairs where exactly one side won -- the two
    discordant cells of the 2x2 table. This is a binomial sign test on those two counts, which
    is what McNemar's test reduces to in the exact (as opposed to chi-squared-approximated)
    case: under the null that a win is equally likely to fall on either side, the smaller count
    is Binomial(a_only + b_only, 0.5), and the two-sided p-value is twice the lower tail.

    With few discordant pairs this test has little power -- ``docs/DE_KERNEL_PLAN.md`` clause 3
    is the standing example, 3 discordant pairs giving p=0.25 on a swing that looked decisive at
    face value, resolved only by a larger re-run. Report the discordant count next to the
    p-value; do not read the p-value as "no difference" until it is generated by enough
    discordant pairs to matter (`docs/EVOLVE_SEARCH_PLAN.md`'s own rule: "the response to a bar
    that cannot resolve its own question is more seeds, never a reworded bar").
    """
    n = a_only + b_only
    if n == 0:
        return 1.0
    extreme = min(a_only, b_only)
    tail = sum(math.comb(n, k) for k in range(extreme + 1)) / 2**n
    return min(1.0, float(2 * tail))
