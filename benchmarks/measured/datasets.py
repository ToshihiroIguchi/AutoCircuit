"""The measured-data arena's dataset list: `docs/IMPACT_PLAN.md` item C.

Every entry here is a *real* impedance-vs-frequency file -- not one generated by
`autocircuit.core.simulate` -- with its licence and provenance recorded beside it, per that
plan's section 4.2. `measured.py` is the harness that runs gates R1-R5 against this list; this
module only says what the arena contains and why each entry is in it.

Nothing here is a truth. `published_circuit`, when given, is what the *source* fitted -- kept
as a citation for gate R4's reporting table, never as ground truth the way
`benchmarks/discovery_v2.py`'s `Reference.circuit` is for synthetic data. A real spectrum's
right answer is not known, which is the whole point of this arena (see §4.1).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

DATA_DIR = Path(__file__).parent / "data"


@dataclass(frozen=True)
class MeasuredDataset:
    id: str
    label: str
    file: str
    """Path relative to :data:`DATA_DIR`."""
    format: str | None
    """Explicit ``autocircuit.io.read`` format name, or None to let it sniff."""
    system: str
    """One line: what physical system this is, as far as the source states it."""
    source_url: str
    license: str
    artefact: str
    """Which of §4.1's real-instrument artefacts this dataset was chosen to exhibit."""
    published_circuit: str | None = None
    """AutoCircuit-DSL form of a circuit the *source* fitted, if it named one. A citation for
    gate R4, never a truth -- see the module docstring."""
    published_circuit_note: str = ""
    reader_hints: dict[str, Any] = field(default_factory=dict)
    """Extra keyword hints forwarded to ``autocircuit.io.read``.

    Used only where this project's own alias-based column detection is ambiguous for a header
    spelling it has not seen before (e.g. ``Real_Ohm``/``Imag_Ohm``, or a ``-Z''`` column whose
    sign this project's existing convention -- deliberately unchanged here, see
    ``io/generic_csv.py``'s own ``_IMAG_NEGATE_RAW`` comment -- does not resolve the same way a
    physical read of the data does). Forcing the positional branch with ``has_header=False``
    plus explicit ``col_f``/``col_re``/``col_im`` is the mechanism: the header row is then just
    a row that fails to parse as floats and is silently skipped, not a row whose alias table
    has to grow to cover it.
    """

    @property
    def path(self) -> Path:
        return DATA_DIR / self.file


