# --- H1: the fixed 10-element, 5-block Maxwell-Wagner-style topology (unchanged design) --------

TEXT = "p(R1,C1)-p(R2,C2)-p(R3,C3)-p(R4,C4)-p(R5,C5)"
VALUES = {
    "R1.R": 10.0,
    "C1.C": 1.0e-8,
    "R2.R": 50.0,
    "C2.C": 1.0e-6,
    "R3.R": 200.0,
    "C3.C": 1.0e-4,
    "R4.R": 800.0,
    "C4.C": 1.0e-2,
    "R5.R": 3000.0,
    "C5.C": 1.0,
}
F_MIN, F_MAX, PPD = 1e-1, 1e7, 10

SCREEN_POPSIZE = 8
SCREEN_MAXITER = 40
SCREEN_RESTARTS = 1

HIT_THRESHOLD_PCT = 5.0

#: Datasets that carry a ``published_circuit`` (``benchmarks/measured/datasets.py``) reuse that
#: exactly, per this project's convention that a fit named by the data's own source is a
#: citation, not something a benchmark script should override. Neither real-data candidate for
#: H2 (``zenodo-21700-id15``, ``zenodo-21700-id34`` -- confirmed below to be the two datasets with
#: an irregular, non-log-uniform frequency axis) carries one, so a fixed reference topology was
#: derived for each with one offline, bounded discovery run (not repeated on every invocation of
#: this script, and not part of the H2 experiment's own timing): ``discover(mode="exhaustive",
#: pool=("R", "C", "L", "CPE", "W"), max_elements=5, weighting="auto", seed=0, time_limit=30)``,
#: ~100 s each. A full default-pool ``discover()`` (``mode="auto"``, the pool-widening/genetic
#: fallback path) was tried first and killed after >3 minutes without finishing --
#: ``docs/IMPACT_PLAN.md`` already records one real dataset's unbounded ``discover()`` running for
#: ~2 hours before being killed, so this script hardcodes the result the same way H1's own
#: ``TEXT``/``VALUES`` are hardcoded, rather than re-searching for a topology on every run.
FALLBACK_TOPOLOGY: dict[str, str] = {
    "zenodo-21700-id15": "p(R1,C1)-L1-CPE1",
    "zenodo-21700-id34": "p(R1-C1,R2)-W1",
}

DEFAULT_STRIDES = "1,2,4"


def thin(spectrum: Spectrum, stride: int) -> Spectrum:
    """Uniform index-stride decimation -- H1's only method, and H2's method (a).

    ``Spectrum.__post_init__`` always sorts ``f``/``z`` ascending on construction, so a plain
    index stride is already frequency-order-consistent for every spectrum this module builds,
    synthetic (already log-uniform) or a real instrument export (ascending after
    ``autocircuit.io.read``, confirmed empirically while building this script) alike.
    """
    return Spectrum(f=spectrum.f[::stride], z=spectrum.z[::stride])


def thin_log_uniform(spectrum: Spectrum, n_target: int) -> Spectrum:
    """H2 method (b): resample onto a grid evenly spaced in ``log10(f)`` at ``n_target`` points,
    then snap each grid point to its nearest *actual* data index -- pure index selection, no
    interpolation of ``Z``. Colliding snaps collapse via ``np.unique``, so the result may hold
    fewer than ``n_target`` points on a sparse stretch of an irregular sweep; that is expected
    and reported as the point count actually used, not padded back up.
    """
    f, z = spectrum.f, spectrum.z
    n = f.size
    n_target = max(1, min(n_target, n))
    log_f = np.log10(f)
    grid = np.linspace(log_f[0], log_f[-1], n_target)
    hi = np.clip(np.searchsorted(log_f, grid), 0, n - 1)
    lo = np.clip(hi - 1, 0, n - 1)
    use_lo = np.abs(log_f[lo] - grid) <= np.abs(log_f[hi] - grid)
    idx = np.unique(np.where(use_lo, lo, hi))
    return Spectrum(f=f[idx], z=z[idx])


def thin_adaptive(spectrum: Spectrum, n_target: int) -> Spectrum:
    """H2 method (c): adaptive, importance-based thinning.

    Exact mechanism (this method has no standard definition to defer to, so it is spelled out
    here): score every point by the local rate of change of impedance with frequency,
    ``|dZ/df|``, via ``np.gradient`` on the real and imaginary parts separately (``Spectrum``'s
    own sorted-ascending invariant makes this well-defined without a separate sort step), then
    combine as one complex derivative's magnitude. Keep the ``n_target // 2`` highest-scoring
    points outright (the sharpest resonance/relaxation features), then fill the remaining
    ``n_target - n_target // 2`` slots with a uniform stride over whatever is left (the flattest,
    least-informative stretches), so the method degrades toward plain uniform decimation as
    ``n_target`` approaches the full point count rather than ever dropping every "boring" point.
    """
    f, z = spectrum.f, spectrum.z
    n = f.size
    n_target = max(1, min(n_target, n))
    dzdf = np.gradient(z.real, f) + 1j * np.gradient(z.imag, f)
    score = np.abs(dzdf)
    n_top = n_target // 2
    top_idx = np.argsort(score)[::-1][:n_top]
    remaining = np.setdiff1d(np.arange(n), top_idx)
    n_fill = n_target - top_idx.size
    if n_fill > 0 and remaining.size > 0:
        fill_stride = max(1, remaining.size // n_fill)
        fill_idx = remaining[::fill_stride][:n_fill]
    else:
        fill_idx = np.empty(0, dtype=np.intp)
    idx = np.union1d(top_idx, fill_idx)
    return Spectrum(f=f[idx], z=z[idx])


def _log_step_ratio(f: np.ndarray) -> float:
    """max/min ratio of consecutive log10(f) steps: ~1 means already log-uniform (H2's methods
    (a)/(b) would coincide and the comparison is uninformative); the two datasets this module
    defaults H2 to measured at ~2.65 while every other entry in ``DATASETS`` measured ~1.0-1.13.
    """
    steps = np.diff(np.log10(f))
    return float(steps.max() / steps.min())


def _topology_for_dataset(ds: MeasuredDataset) -> str:
    if ds.published_circuit is not None:
        return ds.published_circuit
    if ds.id in FALLBACK_TOPOLOGY:
        return FALLBACK_TOPOLOGY[ds.id]
    raise SystemExit(
        f"no fixed topology available for dataset {ds.id!r}: it has no published_circuit "
        "(benchmarks/measured/datasets.py) and no FALLBACK_TOPOLOGY entry in this script. "
        "Add one -- see this module's FALLBACK_TOPOLOGY comment for how the existing entries "
        "were derived -- before running H2 on it."
    )


def _load_existing(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    rows: list[dict[str, Any]] = json.loads(path.read_text(encoding="utf-8"))
    print(f"resuming with {len(rows)} rows already on disk", flush=True)
    return rows


def _save(path: Path, rows: list[dict[str, Any]]) -> None:
    path.write_text(json.dumps(rows, indent=2), encoding="utf-8")


def _run_one(
    circuit: Circuit,
    spectrum: Spectrum,
    full: Spectrum,
    *,
    seed: int,
    condition: str,
    dataset: str | None,
) -> dict[str, Any]:
    """One ``fit()`` call at the tier-1 screen budget, scored against the FULL, untouched
    spectrum via ``relative_error`` -- never against the (possibly thinned) fit input, so costs
    from different-sized conditions are comparable on one scale."""
    t0 = time.perf_counter()
    result = fit(
        circuit,
        spectrum,
        weighting="modulus",
        seed=seed,
        restarts=SCREEN_RESTARTS,
        popsize=SCREEN_POPSIZE,
        maxiter=SCREEN_MAXITER,
        local=SCREEN_LOCAL,  # tier-1 screen budget -- see module docstring's bug warning
    )
    elapsed = time.perf_counter() - t0
    z_model = circuit.impedance(full.omega, result.values)
    err_pct = float(relative_error(z_model, full)) * 100.0
    return {
        "seed": seed,
        "condition": condition,
        "dataset": dataset,
        "relative_error_pct": err_pct,
        "wall_clock_s": elapsed,
        "hit": err_pct < HIT_THRESHOLD_PCT,
    }


def _print_summary(rows: list[dict[str, Any]], *, order: list[str], control: str) -> None:
    by_cond: dict[str, list[dict[str, Any]]] = {name: [] for name in order}
    for row in rows:
        if row["condition"] in by_cond:
            by_cond[row["condition"]].append(row)

    header = (
        f"{'condition':16s} {'median err%':>12s} {'mean time(s)':>13s} "
        f"{'hits':>9s} {'95% CI':>16s}"
    )
    print(header)
    print("-" * len(header))
    for name in order:
        recs = by_cond[name]
        if not recs:
            print(f"{name:16s} (no data)")
            continue
        errs = np.array([r["relative_error_pct"] for r in recs])
        times = np.array([r["wall_clock_s"] for r in recs])
        hits = sum(1 for r in recs if r["hit"])
        total = len(recs)
        lo, hi = wilson(hits, total)
        print(
            f"{name:16s} {np.median(errs):12.3f} {np.mean(times):13.3f} "
            f"{hits:4d}/{total:<4d} [{lo * 100:5.1f}%,{hi * 100:5.1f}%]"
        )

    control_hits = {r["seed"]: r["hit"] for r in by_cond.get(control, [])}
    if not control_hits:
        return
    print()
    for name in order:
        if name == control:
            continue
        recs = by_cond[name]
        if not recs:
            continue
        only_control = 0
        only_cond = 0
        for r in recs:
            if r["seed"] not in control_hits:
                continue
            c_hit, t_hit = control_hits[r["seed"]], r["hit"]
            if c_hit and not t_hit:
                only_control += 1
            elif t_hit and not c_hit:
                only_cond += 1
        p = mcnemar_exact(only_control, only_cond)
        print(
            f"{name} vs {control}: only_{control}={only_control} only_{name}={only_cond} "
            f"McNemar p={p:.4f}"
        )


def run_h1(seeds: int, out: Path, strides: list[int]) -> None:
    full = simulate(TEXT, log_frequencies(F_MIN, F_MAX, PPD), VALUES, noise=0.01, seed=0)
    circuit = Circuit.parse(TEXT)
    print(f"reference: {TEXT}  {full.n} points  {seeds} seeds per condition")

    conditions = {f"{s}x": thin(full, s) for s in strides}
    for name, spectrum in conditions.items():
        print(f"  {name}: {spectrum.n} points")
    print()

    rows = _load_existing(out)
    done = {(r.get("dataset"), r["condition"], r["seed"]) for r in rows}
    n_new = 0
    for seed in range(seeds):
        for name, spectrum in conditions.items():
            key = (None, name, seed)
            if key in done:
                continue
            row = _run_one(circuit, spectrum, full, seed=seed, condition=name, dataset=None)
            rows.append(row)
            done.add(key)
            n_new += 1
            _save(out, rows)
    print(f"{n_new} new rows this run; {len(rows)} total on disk")
    print()

    control = "1x" if "1x" in conditions else next(iter(conditions))
    _print_summary(rows, order=list(conditions.keys()), control=control)


def run_h2(seeds: int, out: Path, strides: list[int], dataset_id: str) -> None:
    ds = next((d for d in DATASETS if d.id == dataset_id), None)
    if ds is None:
        raise SystemExit(
            f"unknown dataset id {dataset_id!r}; choices: {[d.id for d in DATASETS]}"
        )
    topology_text = _topology_for_dataset(ds)
    circuit = Circuit.parse(topology_text)
    full = read(ds.path, format=ds.format, **ds.reader_hints)  # already ascending, see thin()
    ratio = _log_step_ratio(full.f)
    print(f"dataset: {ds.id}  n={full.n}  log10-step ratio={ratio:.2f}")
    if ratio < 1.5:
        print(
            "  note: this dataset's frequency axis is close to log-uniform -- H2's method (a) "
            "and (b) will largely coincide here and the comparison is not very informative"
        )
    print(f"topology: {topology_text}  ({seeds} seeds per condition)")

    conditions: dict[str, Spectrum] = {}
    for stride in strides:
        n_target = thin(full, stride).n
        conditions[f"uniform_{stride}x"] = thin(full, stride)
        conditions[f"loguniform_{stride}x"] = thin_log_uniform(full, n_target)
        conditions[f"adaptive_{stride}x"] = thin_adaptive(full, n_target)
    for name, spectrum in conditions.items():
        print(f"  {name}: {spectrum.n} points")
    print()

    rows = _load_existing(out)
    done = {(r.get("dataset"), r["condition"], r["seed"]) for r in rows}
    n_new = 0
    for seed in range(seeds):
        for name, spectrum in conditions.items():
            key = (ds.id, name, seed)
            if key in done:
                continue
            row = _run_one(circuit, spectrum, full, seed=seed, condition=name, dataset=ds.id)
            rows.append(row)
            done.add(key)
            n_new += 1
            _save(out, rows)
    print(f"{n_new} new rows this run; {len(rows)} total on disk")

    for stride in strides:
        names = [f"uniform_{stride}x", f"loguniform_{stride}x", f"adaptive_{stride}x"]
        print(f"\n-- stride {stride}x, vs. uniform decimation (pass bar #2's own baseline) --")
        _print_summary(rows, order=names, control=names[0])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--seeds",
        type=int,
        default=480,
        help="seeds per condition (default: 480, this project's standard McNemar convention; "
        "the pilot recorded in docs/SEARCH_TIME_PLAN.md section 3.5 used 60)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        required=True,
        help="JSON results file; resumable -- a rerun skips any (dataset, condition, seed) "
        "already recorded and appends the rest",
    )
    parser.add_argument(
        "--strides",
        default=DEFAULT_STRIDES,
        help=f"comma-separated decimation strides (default: {DEFAULT_STRIDES}); with --dataset "
        "and no explicit --strides, H2 defaults to just 2 (see module docstring)",
    )
    parser.add_argument(
        "--dataset",
        default=None,
        help="a benchmarks/measured/datasets.py dataset id; when given, runs H2 (the "
        "thinning-method comparison) on that real spectrum instead of H1",
    )
    args = parser.parse_args()
    strides = [int(s) for s in args.strides.split(",")]

    if args.dataset:
        if args.strides == DEFAULT_STRIDES:
            strides = [2]
        if 4 in strides:
            print(
                "warning: --strides 4 is not meaningful for H2's real datasets (a ~44-point "
                "sweep would be left with ~11 points against a 4-5-element fit) -- skipping "
                "the 4x condition"
            )
            strides = [s for s in strides if s != 4]
        if not strides:
            raise SystemExit("no strides left to run for H2 after dropping 4x")
        run_h2(args.seeds, args.out, strides, args.dataset)
    else:
        run_h1(args.seeds, args.out, strides)


if __name__ == "__main__":
    main()
