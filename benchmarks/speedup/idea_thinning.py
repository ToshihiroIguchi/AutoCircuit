"""``docs/SEARCH_TIME_PLAN.md`` section 3.5: does thinning the frequency points fed to the DE
global stage help tier-1 screening throughput, and (on a real dataset only) does the thinning
*method* matter?

**H1 -- does thinning help at all.** Fit the SAME 10-element, 5-block Maxwell-Wagner-style
topology (the "10-12 free parameters" regime ``docs/SEARCH_SPEEDUP_PLAN.md`` ideas C/D used) at
the production tier-1 screen budget (``SCREEN_POPSIZE=8, SCREEN_MAXITER=40, SCREEN_RESTARTS=1``,
and -- the bug this module must never reintroduce -- ``local=SCREEN_LOCAL`` on every ``fit()``
call, since ``fit()``'s own default local-polish budget is ``PUBLISH_LOCAL`` (``max_nfev=20000``),
not the cheap tier-1 one, regardless of the DE popsize/maxiter passed) three ways: full spectrum,
uniform 2x decimation, uniform 4x decimation. Uses ``fit()`` rather than ``screen()`` (which
returns only a cost, no parameter vector) so the fitted parameters can be re-evaluated against the
FULL, untouched spectrum via ``relative_error`` (weighting-independent), making costs computed on
different-sized data comparable on one scale. A pilot at 60 seeds already ran (see that section):
25%/52% wall-clock reduction at 2x/4x with no visible hit-rate cost, but Wilson CIs overlapped
heavily and the section's own pre-registered reading is that this does not yet license a
ship/reject verdict -- it licenses running the full 480-seed version, which is what ``--seeds 480``
(the default here) is for.

**H2 -- does the thinning *method* matter, on a real, irregular-frequency dataset.** Every
synthetic reference in this repository is generated by ``log_frequencies`` (``simulate.py``, an
``np.logspace`` sweep), so on synthetic data uniform *index* decimation is already
log-*frequency*-uniform decimation -- methods (a) and (b) below collapse to the same condition.
The method comparison is only informative on a spectrum whose frequency axis is not already
log-uniform, so H2 runs against a real dataset from ``benchmarks/measured/datasets.py``'s
``DATASETS`` list. Confirmed against the real files while building this script (see
``FALLBACK_TOPOLOGY`` below and the log10-step-ratio check ``main()`` prints): ``zenodo-21700-id15``
and ``zenodo-21700-id34`` have a log10-step ratio of ~2.65 (a real irregular instrument sweep)
while every other dataset in the list is ~1.0-1.13 (effectively log-uniform already, and so
uninformative for H2). Three thinning methods are compared, always scored against the dataset's
own full, untouched spectrum:

(a) uniform index-stride decimation -- :func:`thin`, the same helper H1 uses;
(b) log-frequency-uniform resampling -- build a new grid evenly spaced in ``log10(f)`` at the same
    reduced point count (a) would produce, then snap each grid point to its nearest actual data
    index (pure index selection, no interpolation of ``Z``);
(c) adaptive, importance-based thinning -- score each point by local ``|dZ/df|``, keep the
    higher-scoring half, and fill the rest with a uniform stride over what remains (see
    :func:`thin_adaptive`'s docstring for the exact mechanism, since this method has no standard
    definition to defer to).

**Pre-registered pass bar, quoted from ``docs/SEARCH_TIME_PLAN.md`` section 3.5, not re-derived
here:**

1. Ships only if wall-clock or DE-fit-count falls by a real margin (the same >=15% bar section 3.1
   set for itself) *at preserved hit rate* (no significant McNemar drop) on an unsaturated
   frozen-landscape arena -- both halves of the claim, never the speed half alone.
2. A method more complex than plain uniform decimation (log-uniform resampling, adaptive
   importance-weighting) ships only if it clears its own significance bar *against uniform
   decimation*, not merely against no thinning at all.

This module is a standalone benchmark harness; it does not touch ``core/fit.py``'s production
``_global_stage``, ``screen()``, or ``fit()``.
"""

